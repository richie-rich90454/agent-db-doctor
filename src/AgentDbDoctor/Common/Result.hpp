// The Result types, which carry either a value or an explanation of a failure
// without using an exception.
//
// C++ exceptions are appropriate for programming errors, but the specification
// asks the tool to use `optional` and error codes for ordinary control flow so
// that the hot path never pays for unwinding. `Result<T>` is that pattern: a
// value type that is either a success holding a `T`, or a failure holding a
// sentence. It is the C++ equivalent of a Java class with a `null` value and a
// separate error string.
#ifndef AGENT_DB_DOCTOR_COMMON_RESULT_HPP
#define AGENT_DB_DOCTOR_COMMON_RESULT_HPP
// Provides `optional`, a container that may or may not hold a value.
#include <optional>
// Provides `string`, which owns and stores a sequence of characters.
#include <string>
// The outer namespace is declared before the nested spelling below, because
// `namespace Outer::Inner` only compiles when `Outer` already exists. Without
// this line a header that is a translation unit's first include would fail.
namespace AgentDbDoctor {
}

using namespace std;
namespace AgentDbDoctor::Common {
// The Status class is the result type for operations that produce no value.
//
// It is a separate class from `Result<T>` rather than a specialisation of it,
// because the specification forbids inheritance, and a specialisation would
// require a second type with the same name and a different shape.
class Status final {
public:
    // Creates a successful status. A successful status carries no message.
    static Status success() {
        return Status(true, string());
    }
    // Creates a failed status carrying a complete sentence.
    static Status failure(string explanation) {
        return Status(false, std::move(explanation));
    }
    // `const` here is a compile time promise that this method does not modify
    // the object it is called on.
    bool isSuccess() const {
        return succeededFlag;
    }
    // True when the operation failed. This is the same test as `isSuccess`
    // written the other way round, for code that reads better as a question.
    bool isFailure() const {
        return !succeededFlag;
    }
    // The sentence explaining the failure. Empty when the status is a success.
    const string& errorMessage() const {
        return explanationText;
    }
private:
    Status(bool succeeded, string explanation)
        : succeededFlag(succeeded), explanationText(std::move(explanation)) {
    }
    bool succeededFlag=true;
    string explanationText;
};
// The Result class is the result type for operations that produce a value.
//
// `T` is a template parameter, which means `Result<int>` is a complete class
// generated by the compiler for each type it is used with. A Java developer would
// recognise this as a generic class.
//
// The value and the message are held in an `optional` and a `string` rather than in
// a `variant`, because a `variant` requires each of its alternatives to be a
// distinct type, and `Result<string>` would otherwise ask for a variant of two
// strings, which the standard library refuses to build.
template <typename T>
class Result final {
public:
    // Creates a successful result wrapping a value.
    static Result succeeded(T value) {
        Result builtResult;
        builtResult.isSuccessFlag=true;
        builtResult.heldValue=std::move(value);
        return builtResult;
    }
    // Creates a failed result carrying a complete sentence.
    static Result failure(string explanation) {
        Result builtResult;
        builtResult.isSuccessFlag=false;
        builtResult.failureText=std::move(explanation);
        return builtResult;
    }
    // `const` here is a compile time promise that this method does not modify the
    // object it is called on.
    bool isSuccess() const {
        return isSuccessFlag;
    }
    bool isFailure() const {
        return !isSuccessFlag;
    }
    // Returns the value. Calling this on a failed result is a programming error,
    // because there is no value to return. In a release build `optional::value`
    // throws, so the mistake surfaces immediately rather than returning a wrong
    // answer.
    const T& get() const {
        return heldValue.value();
    }
    // Returns the value only when the result is a success. `optional<T>` is the
    // container that may or may not hold a value of type `T`.
    optional<T> tryGet() const {
        return heldValue;
    }
    // Returns the sentence explaining the failure. Empty when this is a success.
    const string& errorMessage() const {
        return failureText;
    }
private:
    // The default constructor is private so that a result can only be built through
    // one of the two named factory methods, which is what keeps the success flag and
    // the value in agreement.
    Result() = default;
    // True when the result holds a value rather than a message.
    bool isSuccessFlag=false;
    // The value, present only when the result is a success.
    optional<T> heldValue;
    // The message, present only when the result is a failure.
    string failureText;
};
}
#endif
